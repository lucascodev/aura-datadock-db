CREATE SCHEMA logistics;

CREATE TABLE logistics.warehouses (
  id SERIAL PRIMARY KEY,
  city VARCHAR(80) NOT NULL
);

CREATE TABLE customers (
  id SERIAL PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email TEXT UNIQUE NOT NULL,
  referred_by INTEGER REFERENCES customers(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE customer_profiles (
  customer_id INTEGER PRIMARY KEY REFERENCES customers(id) ON DELETE CASCADE,
  bio TEXT,
  preferences JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE orders (
  id SERIAL PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id),
  warehouse_id INTEGER REFERENCES logistics.warehouses(id),
  total NUMERIC(10, 2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX orders_status_idx ON orders (status);

CREATE TABLE products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(40) UNIQUE NOT NULL,
  title TEXT NOT NULL,
  tags TEXT[] NOT NULL DEFAULT '{}',
  image BYTEA
);

CREATE TABLE order_items (
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id),
  quantity INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE audit_log (
  entry TEXT NOT NULL,
  recorded_at TIMESTAMP NOT NULL DEFAULT '2024-01-02 03:04:05'
);

CREATE VIEW paid_orders AS
  SELECT id, customer_id, total FROM orders WHERE status = 'paid';

