import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const NOTICES_FILE = 'THIRD_PARTY_NOTICES.md';
const NODE_MODULES = 'node_modules/';
const LEGAL_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;
const README_FILE = /^readme/i;
const README_LICENSE_SECTION = /^#+\s*licen[cs]e\s*\n([\s\S]*?)(?=^#|(?![\s\S]))/im;
const SECTION_DIVIDER = '\n\n---\n\n';

const HEADER = `# Third-party notices

This extension is licensed under the MIT License (see [LICENSE](LICENSE)). Its bundled files in \`dist/\` also contain the open source packages below, under their own licenses.

This file is generated by \`npm run build -- --production\` from what actually goes into the bundles. Do not edit it by hand.`;

export function writeThirdPartyNotices(metafiles) {
  const packages = [...collectPackageDirectories(metafiles)].map(readBundledPackage);
  const uniquePackages = [...new Map(packages.map((entry) => [toIdentity(entry), entry])).values()];
  writeFileSync(NOTICES_FILE, renderNotices(uniquePackages.sort(compareByIdentity)));
}

function toIdentity(entry) {
  return `${entry.name}@${entry.version}`;
}

function collectPackageDirectories(metafiles) {
  const directories = new Set();
  for (const metafile of metafiles) {
    for (const output of Object.values(metafile.outputs)) {
      for (const [inputPath, input] of Object.entries(output.inputs)) {
        const directory = input.bytesInOutput > 0 ? toPackageDirectory(inputPath) : undefined;
        if (directory) {
          directories.add(directory);
        }
      }
    }
  }
  return directories;
}

function toPackageDirectory(inputPath) {
  const index = inputPath.lastIndexOf(NODE_MODULES);
  if (index === -1) {
    return undefined;
  }
  const rootEnd = index + NODE_MODULES.length;
  const segments = inputPath.slice(rootEnd).split('/');
  const nameLength = segments[0].startsWith('@') ? 2 : 1;
  return inputPath.slice(0, rootEnd) + segments.slice(0, nameLength).join('/');
}

function readBundledPackage(directory) {
  const manifest = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
  const files = readdirSync(directory);
  const legalFiles = files.filter((file) => LEGAL_FILE.test(file)).sort();
  const legalTexts = legalFiles.map((file) => normalizeLineBreaks(readFileSync(join(directory, file), 'utf8')));
  const texts = legalTexts.length > 0 ? legalTexts : readReadmeLicense(directory, files);

  if (texts.length === 0) {
    throw new Error(`${manifest.name}@${manifest.version} is bundled without a license text. Add it before publishing.`);
  }
  return { name: manifest.name, version: manifest.version, license: manifest.license, legalTexts: texts };
}

function readReadmeLicense(directory, files) {
  const readme = files.find((file) => README_FILE.test(file));
  const section = readme ? README_LICENSE_SECTION.exec(normalizeLineBreaks(readFileSync(join(directory, readme), 'utf8'))) : null;
  return section ? [section[1].trim()] : [];
}

function normalizeLineBreaks(text) {
  return text.replace(/\r\n/g, '\n').trim();
}

function compareByIdentity(a, b) {
  return toIdentity(a).localeCompare(toIdentity(b));
}

function renderNotices(packages) {
  const summary = packages.map((entry) => `| ${entry.name} | ${entry.version} | ${entry.license} |`).join('\n');
  const table = `| Package | Version | License |\n| --- | --- | --- |\n${summary}`;
  const sections = packages.map(renderPackage);
  return `${[`${HEADER}\n\n${table}`, ...sections].join(SECTION_DIVIDER)}\n`;
}

function renderPackage(entry) {
  const texts = entry.legalTexts.map((text) => `\`\`\`\`text\n${text}\n\`\`\`\``).join('\n\n');
  return `## ${entry.name}@${entry.version}\n\n${texts}`;
}
