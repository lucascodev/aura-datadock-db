import type { ForeignKey } from '../../../domain/schema/model/ForeignKey';
import type { NamespaceSchema } from '../../../domain/schema/model/NamespaceSchema';
import type { TableColumn } from '../../../domain/schema/model/TableColumn';
import type { TableDefinition } from '../../../domain/schema/model/TableDefinition';
import type { PostgresColumnRow, PostgresConstraintRow, PostgresSchemaRows } from './postgresSchemaRows';

const REFERENTIAL_ACTIONS: Readonly<Record<string, string | undefined>> = {
  c: 'CASCADE',
  n: 'SET NULL',
  d: 'SET DEFAULT',
  r: 'RESTRICT',
};

const IDENTITY_CLAUSES: Readonly<Record<string, string | undefined>> = {
  a: 'GENERATED ALWAYS AS IDENTITY',
  d: 'GENERATED BY DEFAULT AS IDENTITY',
};

const VIEW_RELATION_KINDS = new Set(['v', 'm']);

export function isViewRelation(relationKind: string): boolean {
  return VIEW_RELATION_KINDS.has(relationKind);
}

export function toPostgresSchema(namespace: string, rows: PostgresSchemaRows): NamespaceSchema {
  const tables = rows.tables.map((table): TableDefinition => {
    const constraints = rows.constraints.filter((constraint) => constraint.table_name === table.table_name);
    const primaryKey = constraints.find((constraint) => constraint.constraint_type === 'p')?.column_names ?? [];

    return {
      namespace,
      name: table.table_name,
      kind: isViewRelation(table.relation_kind) ? 'view' : 'table',
      columns: rows.columns
        .filter((column) => column.table_name === table.table_name)
        .map((column) => toColumn(column, primaryKey)),
      primaryKey,
      foreignKeys: constraints.filter((constraint) => constraint.constraint_type === 'f').map(toForeignKey),
      indexes: rows.indexes
        .filter((index) => index.table_name === table.table_name)
        .map((index) => ({
          name: index.index_name,
          columns: index.column_names,
          isUnique: index.is_unique,
          isPrimary: index.is_primary,
          definition: index.definition,
        })),
      viewDefinition: table.view_definition ?? undefined,
    };
  });

  return { kind: 'postgres', namespace, tables };
}

function toColumn(row: PostgresColumnRow, primaryKey: readonly string[]): TableColumn {
  return {
    name: row.column_name,
    dataType: row.data_type,
    nullable: !row.is_not_null,
    isPrimaryKey: primaryKey.includes(row.column_name),
    defaultValue: row.column_default ?? undefined,
    generationClause: IDENTITY_CLAUSES[row.identity_kind],
    isComputed: row.is_computed,
  };
}

function toForeignKey(row: PostgresConstraintRow): ForeignKey {
  return {
    name: row.constraint_name,
    columns: row.column_names,
    referencedNamespace: row.referenced_namespace ?? '',
    referencedTable: row.referenced_table ?? '',
    referencedColumns: row.referenced_columns,
    onDelete: REFERENTIAL_ACTIONS[row.delete_action],
    onUpdate: REFERENTIAL_ACTIONS[row.update_action],
  };
}
